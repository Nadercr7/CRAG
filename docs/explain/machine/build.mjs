// Builds the VRAGMachine component: node docs/explain/machine/build.mjs
// Writes machine.js, machine.css and demo.html next to this file. No runtime dependencies.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import * as k from "./vendor/iso-kit.mjs";
import { layout } from "./src/layout.mjs";
import { buildArt } from "./src/art.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(HERE, p), "utf8");
const strip = (file) => readFileSync(join(HERE, "vendor", file), "utf8").replace(/^export /gm, "").replace(/const ISO_CSS = `[\s\S]*$/, "");

// ---- data: only for the fixed thresholds drawn on the dials (the live code re-reads everything from VRAG_DATA)
const sandbox = { window: {} };
vm.runInNewContext(readFileSync(join(HERE, "..", "data.js"), "utf8"), sandbox);
const DATA = sandbox.window.VRAG_DATA;
const TOP_N = Math.max(...Object.values(DATA.scenarios).map((s) => s.F.top.length));

const art = buildArt(DATA.thresholds, TOP_N);

// ---- css
const iso = k.ISO_CSS.split("\n");
const keep = /^(\.iso-(svg|fill|solid|shade|top|halo|line|wire|dots|face-text)|\.tb-|@keyframes|@media \(prefers-reduced-motion)/;
const scope = (line) =>
  line
    .split("}")
    .map((rule) => rule.trim())
    .filter(Boolean)
    .map((rule) => {
      const i = rule.indexOf("{");
      const sel = rule
        .slice(0, i)
        .split(",")
        .map((s) => ".vrm " + s.trim())
        .join(",");
      return sel + rule.slice(i) + "}";
    })
    .join("\n");
const kitCss = iso
  .filter((l) => keep.test(l) && !l.startsWith(".iso-svg{") && !l.startsWith("@keyframes") && !l.startsWith("@media"))
  .map(scope)
  .join("\n");

const darkVars = `
  --anatomy-paper: var(--sheet);
  --anatomy-face: color-mix(in srgb, #ffffff 5%, var(--sheet));
  --anatomy-top: color-mix(in srgb, #ffffff 7%, var(--sheet));
  --anatomy-shade-0: color-mix(in srgb, #000000 44%, var(--sheet));
  --anatomy-shade-1: color-mix(in srgb, #000000 34%, var(--sheet));
  --anatomy-shade-2: color-mix(in srgb, #000000 24%, var(--sheet));
  --anatomy-shade-3: color-mix(in srgb, #000000 12%, var(--sheet));
  --anatomy-lit-top: color-mix(in srgb, var(--accent) 20%, var(--sheet));
  --anatomy-lit-shade: color-mix(in srgb, var(--accent) 11%, var(--sheet));
  --anatomy-lo: color-mix(in srgb, var(--ink-3) 52%, var(--sheet));
  --anatomy-halo: #000000;
  --anatomy-halo-opacity: 0.55;
  --vrm-glass: color-mix(in srgb, #000000 26%, var(--sheet));
  --vrm-face: color-mix(in srgb, #ffffff 4%, var(--vrm-glass));
  --vrm-hole: color-mix(in srgb, #000000 55%, var(--sheet));
  --vrm-card: color-mix(in srgb, #ffffff 9%, var(--sheet));
  --vrm-track: color-mix(in srgb, #ffffff 8%, var(--vrm-glass));
`;
const css = read("src/machine.css")
  .replace("/*KIT*/", kitCss)
  .replace("/*THEME_DARK_MEDIA*/", `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) .vrm {${darkVars}}\n}`)
  .replace("/*THEME_DARK_VARS*/", darkVars);
writeFileSync(join(HERE, "machine.css"), css);

// ---- the script: kit + runtime in one IIFE
const head = read("src/live-head.js")
  .replace("__LAYOUT__", () => JSON.stringify(layout))
  .replace("__ART__", () => JSON.stringify({ items: art.items.map(({ id, key, svg }) => ({ id, key: Math.round(key * 100) / 100, svg })), defs: art.defs }))
  .replace("__THRESHOLDS__", () => JSON.stringify(DATA.thresholds));
const js = `/* Verified RAG inspection line: window.VRAGMachine.mount(el, opts). Generated by docs/explain/machine/build.mjs.
   Contains the anatomy kit (MIT) it draws with; no other dependencies. */
(function () {
"use strict";
${strip("iso-kit.mjs")}
${head}
${read("src/live-body.js")}
})();
`;
writeFileSync(join(HERE, "machine.js"), js);

const demo = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Inspection line (demo)</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Condensed:wght@500;600;700&family=IBM+Plex+Sans:ital,wght@0,400;0,500;0,600;1,400&family=IBM+Plex+Mono:wght@400;500&family=IBM+Plex+Sans+Arabic:wght@400;500;600;700&display=swap">
<link rel="stylesheet" href="../tokens.css">
<link rel="stylesheet" href="machine.css">
<style>
  body { margin: 0; background: var(--paper); color: var(--ink); font-family: var(--f-body); }
  .page { box-sizing: border-box; max-width: 1280px; margin: 0 auto; padding: 16px; }
  .bar { display: flex; gap: 6px; flex-wrap: wrap; margin-bottom: 12px; font-size: 13px; }
  .bar button { font: inherit; padding: 4px 10px; border: 1px solid var(--rule); background: var(--sheet); color: var(--ink); border-radius: 4px; cursor: pointer; }
  body.slide .page { width: 1280px; height: 720px; max-width: none; padding: 0; overflow: hidden; }
  body.slide .page > #mount { height: 720px; padding: 12px 16px; box-sizing: border-box; }
  body.slide .bar { display: none; }
</style>
</head>
<body>
<div class="page">
  <div class="bar">
    <button data-t="light">light</button><button data-t="dark">dark</button>
    <button data-l="en">English</button><button data-l="ar">العربية</button>
    <button data-c="0">controls off</button><button data-c="1">controls on</button>
  </div>
  <div id="mount"></div>
</div>
<script src="../data.js"></script>
<script src="machine.js"></script>
<script>
  const qs = new URLSearchParams(location.search);
  if (qs.get("theme")) document.documentElement.setAttribute("data-theme", qs.get("theme"));
  if (qs.has("slide")) document.body.classList.add("slide");
  let controls = qs.get("controls") !== "0";
  let m = null;
  function boot(lang, scenario, mode) {
    if (m) m.destroy();
    m = window.VRAGMachine.mount(document.getElementById("mount"), { data: window.VRAG_DATA, scenario: scenario || qs.get("scenario") || "support", lang: lang || qs.get("lang") || "en", mode: mode || qs.get("mode") || "manual", controls });
    window.m = m;
    document.documentElement.lang = m.getState().lang;
  }
  boot();
  document.querySelector(".bar").addEventListener("click", (e) => {
    const b = e.target.closest("button"); if (!b) return;
    if (b.dataset.t) document.documentElement.setAttribute("data-theme", b.dataset.t);
    if (b.dataset.l) { const s = m.getState(); boot(b.dataset.l, s.scenario, s.mode); }
    if (b.dataset.c) { controls = b.dataset.c === "1"; const s = m.getState(); boot(s.lang, s.scenario, s.mode); }
  });
  m.on("step", (e) => console.log("step", e.index, e.id));
</script>
</body>
</html>
`;
writeFileSync(join(HERE, "demo.html"), demo);
console.log("wrote machine.js", (js.length / 1024).toFixed(0) + " KB, machine.css", (css.length / 1024).toFixed(0) + " KB;", art.parts, "solids in the static art");

// ---- preview of the static art only (used while building the drawing)
if (process.argv.includes("--static")) {
  const svg = `<svg class="iso-svg vrm-svg" viewBox="0 0 ${layout.W} ${layout.H}" xmlns="http://www.w3.org/2000/svg"><defs>${art.defs.replace(/__ID__/g, "p")}</defs>${art.items.map((i) => i.svg.replace(/__ID__/g, "p")).join("")}</svg>`;
  writeFileSync(
    join(HERE, "static.html"),
    `<!doctype html><meta charset="utf-8"><link rel="stylesheet" href="../tokens.css"><link rel="stylesheet" href="machine.css"><body style="margin:0;background:var(--paper)"><div class="vrm" style="padding:20px"><div class="vrm-stage">${svg}</div></div>`,
  );
  console.log("static art:", art.parts, "solids,", art.items.length, "items");
  process.exit(0);
}
